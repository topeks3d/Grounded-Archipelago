_REVERSE: Dict[str, str] = {new: old for old, new in LOCATION_RENAMES.items()}
assert len(_REVERSE) == len(LOCATION_RENAMES), "two checks renamed to the same name"


def ap_name(mod_name: str) -> str:
    """The name Archipelago uses for the location the mod calls mod_name."""
    return LOCATION_RENAMES.get(mod_name, mod_name)


def mod_name(ap_location_name: str) -> str:
    """Inverse of ap_name."""
    return _REVERSE.get(ap_location_name, ap_location_name)
