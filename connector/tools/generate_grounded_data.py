"""
Regenerates ../grounded_data.py from ../../apworld/grounded/{items,locations}.py.

Run this from an environment that has a real Archipelago checkout on
sys.path (items.py imports BaseClasses.ItemClassification), e.g.:

    python tools/generate_grounded_data.py /path/to/Archipelago

Why this exists: connector/grounded_connector.py needs the same
name -> id numbering the apworld generated the seed with, but it shouldn't
have to import the whole apworld (and therefore BaseClasses/Options/etc)
just to get two dictionaries. This script is the single point where the
apworld's real tables get turned into a small, dependency-free snapshot.
Re-run it any time apworld/grounded/items.py or locations.py change.
"""
import sys
from pathlib import Path

def main():
    if len(sys.argv) != 2:
        print("usage: generate_grounded_data.py <path to Archipelago checkout>")
        raise SystemExit(1)

    ap_root = Path(sys.argv[1]).resolve()
    project_root = Path(__file__).resolve().parents[2]
    apworld_dir = project_root / "apworld"

    sys.path.insert(0, str(ap_root))
    sys.path.insert(0, str(apworld_dir))

    from grounded.items import item_name_to_id, item_table, BASE_ID as ITEM_BASE_ID
    from grounded.locations import location_name_to_id, mod_location_name_to_id, BASE_ID as LOCATION_BASE_ID

    out_path = Path(__file__).resolve().parents[2] / "apworld" / "grounded" / "grounded_data.py"

    lines = [
        '"""',
        "AUTO-GENERATED by tools/generate_grounded_data.py -- do not hand-edit.",
        "Regenerate this file any time apworld/grounded/items.py or locations.py change.",
        '"""',
        "",
        f"ITEM_BASE_ID = {ITEM_BASE_ID}",
        f"LOCATION_BASE_ID = {LOCATION_BASE_ID}",
        "",
        "ITEM_NAME_TO_ID = {",
    ]
    for name, code in sorted(item_name_to_id.items(), key=lambda kv: kv[1]):
        lines.append(f"    {name!r}: {code},")
    lines.append("}")
    lines.append("")
    lines.append("LOCATION_NAME_TO_ID = {")
    for name, code in sorted(location_name_to_id.items(), key=lambda kv: kv[1]):
        lines.append(f"    {name!r}: {code},")
    lines.append("}")
    lines.append("")
    # The names the mod reports, for the locations location_renames.py gives
    # a different name in Archipelago (every other location: same name).
    lines.append("# mod-reported name -> id, only where it differs from LOCATION_NAME_TO_ID")
    lines.append("MOD_ONLY_LOCATION_NAMES = {")
    for name, code in sorted(mod_location_name_to_id.items(), key=lambda kv: kv[1]):
        if name not in location_name_to_id:
            lines.append(f"    {name!r}: {code},")
    lines.append("}")
    lines.append("")
    lines.append("ITEM_ID_TO_NAME = {v: k for k, v in ITEM_NAME_TO_ID.items()}")
    lines.append("LOCATION_ID_TO_NAME = {v: k for k, v in LOCATION_NAME_TO_ID.items()}")
    lines.append("MOD_LOCATION_NAME_TO_ID = {**{k: v for k, v in LOCATION_NAME_TO_ID.items() if v not in MOD_ONLY_LOCATION_NAMES.values()}, **MOD_ONLY_LOCATION_NAMES}")
    lines.append("LOCATION_ID_TO_MOD_NAME = {v: k for k, v in MOD_LOCATION_NAME_TO_ID.items()}")
    lines.append("")
    # Not strictly needed by the connector today, but useful for anyone
    # writing tooling later (e.g. a hint-tracker) without re-importing the
    # apworld.
    lines.append("FILLER_ITEM_NAMES = [")
    for name, data in item_table.items():
        if data.count == 0:
            lines.append(f"    {name!r},")
    lines.append("]")
    lines.append("")

    out_path.write_text("\n".join(lines), encoding="utf-8")
    print(f"Wrote {out_path} ({len(item_name_to_id)} items, {len(location_name_to_id)} locations)")

    write_lua_data(project_root)


def _lua_str(value: str) -> str:
    return '"' + value.replace("\\", "\\\\").replace('"', '\\"') + '"'


def write_lua_data(project_root: Path) -> None:
    """game_mod/.../Scripts/ap_data.lua: the tables the Lua mod needs that
    come straight from the apworld (so they can't drift out of sync)."""
    from grounded.mutations import MUTATION_MILESTONES, MUTATION_PREFIX
    from grounded.gear import GEAR_BY_NAME, PROGRESSIVE_LINES

    lines = [
        "-- ap_data.lua",
        "-- AUTO-GENERATED by connector/tools/generate_grounded_data.py from the",
        "-- apworld -- do not hand-edit. Regenerate after changing mutations.py,",
        "-- gear.py, drop_shuffle.py, recipe_shuffle.py or location_renames.py.",
        "",
        "local M = {}",
        "",
        f"M.MUTATION_PREFIX = {_lua_str(MUTATION_PREFIX)}",
        "M.MUTATION_MILESTONES = {" + ", ".join(str(t) for t in MUTATION_MILESTONES) + "}",
        "",
        "-- location_renames.py: mod-reported name -> name shown in Archipelago",
        "M.LOCATION_RENAMES = {",
    ]
    from grounded.location_renames import LOCATION_RENAMES
    for old, new in LOCATION_RENAMES.items():
        lines.append(f"    [{_lua_str(old)}] = {_lua_str(new)},")
    lines += [
        "}",
        "",
        "-- progressive item -> CraftingRecipeTable rows, in unlock order",
        "M.PROGRESSIVE_LINES = {",
    ]
    for prog, line in PROGRESSIVE_LINES.items():
        rows = ", ".join(_lua_str(GEAR_BY_NAME[g].recipe_row) for g in line)
        lines.append(f"    [{_lua_str(prog)}] = {{{rows}}},")
    lines.append("}")

    # Test mode (test_mode.lua) builds its own local shuffles from these, so
    # options can be tried in-game without generating a new room.
    from grounded.drop_shuffle import DROP_GROUPS
    from grounded import recipe_shuffle as rs

    lines += ["", "-- drop_shuffle.py's DROP_GROUPS (item rows; swaps stay within a group)", "M.DROP_GROUPS = {"]
    for group in DROP_GROUPS:
        lines.append("    {" + ", ".join(_lua_str(row) for row in sorted(group.values())) + "},")
    lines.append("}")

    def material_list(materials):
        return "{" + ", ".join(f"{{{_lua_str(m.row)}, {m.low}, {m.high}}}" for m in materials) + "}"

    lines += [
        "",
        "-- recipe_shuffle.py's pools: {item_row, low, high}",
        f"M.RECIPE_MAX_INGREDIENTS = {rs.MAX_INGREDIENTS}",
        "M.RECIPE_TIER_POOLS = {",
    ]
    for tier, (signature, rest) in rs._TIER_POOLS.items():
        lines.append(f"    [{tier}] = {{signature = {material_list(signature)},")
        lines.append(f"        rest = {material_list(rest)}}},")
    lines += ["}", "", "-- {recipe_row, tier, cheap} for every gear recipe RecipeShuffle touches", "M.RECIPE_SHUFFLED_GEAR = {"]
    for gear in rs.shuffled_gear():
        cheap = "true" if gear.kind in rs._CHEAP_KINDS else "false"
        lines.append(f"    {{{_lua_str(gear.recipe_row)}, {gear.tier}, {cheap}}},")
    lines += ["}", "", "return M", ""]

    lua_path = project_root / "game_mod" / "GroundedArchipelago" / "Scripts" / "ap_data.lua"
    lua_path.write_text("\n".join(lines), encoding="utf-8")
    print(f"Wrote {lua_path}")


if __name__ == "__main__":
    main()
